from __future__ import annotations

import json
from pathlib import Path
import unittest

from ripple.forecast import ArtifactLogisticPredictor, ExplainableBaselinePredictor, ShortageFeatures
from tests.support import fixture


class ForecastTests(unittest.TestCase):
    def test_baseline_is_explainable_and_explicitly_not_production_ready(self) -> None:
        features = ShortageFeatures.from_dict(fixture("data/samples/shortage-forecast-request.json"))
        prediction = ExplainableBaselinePredictor().predict(features)
        self.assertGreaterEqual(prediction.shortage_probability, 0.6)
        self.assertEqual(prediction.estimated_hours_to_shortage, 45.0)
        self.assertEqual(len(prediction.top_factors), 3)
        self.assertFalse(prediction.production_ready)

    def test_no_supply_gap_has_no_depletion_time(self) -> None:
        raw = fixture("data/samples/shortage-forecast-request.json")
        raw["expectedSupplyM3h"] = raw["expectedDemandM3h"]
        prediction = ExplainableBaselinePredictor().predict(ShortageFeatures.from_dict(raw))
        self.assertIsNone(prediction.estimated_hours_to_shortage)

    def test_trained_artifact_implements_the_same_contract(self) -> None:
        artifact_path = Path(__file__).resolve().parents[1] / "ripple" / "model_artifacts" / "shortage_logistic_v1.json"
        if not artifact_path.exists():
            self.skipTest("model artifact is generated by ml/scripts/train_model.py")
        predictor = ArtifactLogisticPredictor.from_path(artifact_path)
        features = ShortageFeatures.from_dict(fixture("data/samples/shortage-forecast-request.json"))
        prediction = predictor.predict(features)
        self.assertEqual(prediction.model_version, "shortage-logistic-synthetic-v1")
        self.assertGreaterEqual(prediction.shortage_probability, 0)
        self.assertLessEqual(prediction.shortage_probability, 1)
        self.assertEqual(len(prediction.top_factors), 3)
        self.assertFalse(prediction.production_ready)

    def test_artifact_rejects_shape_mismatch(self) -> None:
        with self.assertRaisesRegex(ValueError, "must match featureOrder"):
            ArtifactLogisticPredictor(
                {
                    "schemaVersion": "1.0",
                    "modelType": "logistic_regression",
                    "modelVersion": "bad",
                    "featureOrder": ["reserveHours"],
                    "means": [],
                    "scales": [1],
                    "weights": [1],
                    "bias": 0,
                }
            )


if __name__ == "__main__":
    unittest.main()
